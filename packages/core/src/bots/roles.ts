export const ROLE_LIST = Object.values(ROLE_PROFILES);

/** 按名字找内置角色（自定义 Bot 没有契约） */
export function roleForBotName(name: string): RoleProfile | undefined {
  return ROLE_LIST.find((r) => r.name === name);
}

/**
 * 输出契约校验：返回缺失的小节关键词。
 * 只做「有没有这个结构」的检查，不判断内容质量。
 */
export function missingContract(role: RoleProfile, content: string): string[] {
  if (!content || content.trim().length === 0) return role.contract.slice();
  return role.contract.filter((key) => !content.includes(key));
}
