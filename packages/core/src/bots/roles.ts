import type { ThinkingEffort } from '@tribot/shared';

// ===== 角色画像：不是「换个名字的同一段提示词」，而是每个角色一套方法论 =====
// 每个角色 = 身份 + 方法（可执行步骤）+ 质量门槛 + 输出契约 + 边界。
// 输出契约会被引擎在回复后校验（checkContract），缺项会提示补。

export type RoleId = 'dispatcher' | 'researcher' | 'engineer' | 'steward' | 'reviewer';

export interface RoleProfile {
  id: RoleId;
  name: string;
  emoji: string;
  /** 一句话职责，显示在 Bot 卡片上 */
  role: string;
  thinking: ThinkingEffort;
  tools: string[];
  /** 输出契约：回复里必须出现的小节关键词（引擎校验用） */
  contract: string[];
  prompt: string;
}

